-- Configuración visual por defecto equivalente a la app Flask.
-- Se crea cuando la cuenta autorizada abra la biblioteca por primera vez.
create or replace function public.biblioteca_asegurar_config()
returns void
language plpgsql
security invoker
set search_path = public
as $$
begin
  if not public.has_biblioteca_access() then
    raise exception 'Biblioteca privada no habilitada para esta cuenta';
  end if;
  insert into public.biblioteca_config(owner_id, clave, valor)
  values
    (auth.uid(), 'nombre_biblioteca', 'Mi biblioteca'),
    (auth.uid(), 'color_principal', '#6f7f64'),
    (auth.uid(), 'color_fondo', '#f5f1e8'),
    (auth.uid(), 'color_texto', '#292823'),
    (auth.uid(), 'color_tarjeta', '#fffdf8'),
    (auth.uid(), 'fuente', 'Georgia, serif'),
    (auth.uid(), 'fuente_titulos', 'Georgia, serif'),
    (auth.uid(), 'fuente_botones', 'Georgia, serif'),
    (auth.uid(), 'tamano_texto', '16'),
    (auth.uid(), 'tamano_titulos', '30'),
    (auth.uid(), 'tamano_botones', '16'),
    (auth.uid(), 'por_pagina', '200'),
    (auth.uid(), 'mostrar_favoritos_catalogo', '1'),
    (auth.uid(), 'vista_default', 'cuadricula')
  on conflict (owner_id, clave) do nothing;
end;
$$;

revoke all on function public.biblioteca_asegurar_config() from public, anon;
grant execute on function public.biblioteca_asegurar_config() to authenticated;

