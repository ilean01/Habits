create table if not exists public.biblioteca_prestamos (
  id bigint generated by default as identity primary key,
  owner_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  legacy_id bigint,
  libro_id bigint not null references public.biblioteca_libros(id) on delete cascade,
  persona text not null,
  persona_id bigint references public.biblioteca_personas(id) on delete set null,
  fecha_prestamo date not null,
  fecha_devolucion_prevista date,
  fecha_devuelto date,
  notas text,
  activo boolean not null default true,
  estado text default 'prestado',
  estado_devolucion text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(owner_id, legacy_id)
);

create table if not exists public.biblioteca_config (
  owner_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  clave text not null,
  valor text,
  updated_at timestamptz not null default now(),
  primary key(owner_id, clave)
);

