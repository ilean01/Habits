-- Biblioteca v18 privada dentro del mismo proyecto Supabase de Habits.
-- Habits sigue siendo multiusuario. La biblioteca avanzada queda habilitada
-- para exactamente UNA cuenta, sin hardcodear su UUID en el frontend.

create table if not exists public.biblioteca_access (
  slot smallint primary key default 1 check (slot = 1),
  user_id uuid not null unique references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

alter table public.biblioteca_access enable row level security;
revoke all on public.biblioteca_access from anon, authenticated;
grant select on public.biblioteca_access to authenticated;

drop policy if exists biblioteca_access_self on public.biblioteca_access;
create policy biblioteca_access_self
on public.biblioteca_access
for select
to authenticated
using (user_id = (select auth.uid()));

create or replace function public.has_biblioteca_access()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.biblioteca_access
    where slot = 1 and user_id = auth.uid()
  );
$$;

revoke all on function public.has_biblioteca_access() from public, anon;
grant execute on function public.has_biblioteca_access() to authenticated;

create table if not exists public.biblioteca_libros (
  id bigint generated by default as identity primary key,
  owner_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  legacy_id bigint,
  item integer,
  codigo_p text,
  dewey text,
  dewey_orden numeric,
  titulo text not null,
  autor text,
  genero text,
  subdivision text,
  editorial text,
  paginas integer,
  observaciones text,
  isbn text,
  idioma text default 'Español',
  portada text,
  descripcion text,
  dedicatoria text,
  rating integer,
  estado_lectura text default 'no_leido',
  pagina_actual integer,
  lista text default 'catalogo',
  relacionados text,
  fecha_agregado date,
  fecha_inicio date,
  fecha_fin date,
  autografiado boolean not null default false,
  favorito boolean not null default false,
  proxima_lectura boolean not null default false,
  eliminado boolean not null default false,
  fecha_eliminado timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint biblioteca_libros_rating check (rating is null or rating between 0 and 5),
  constraint biblioteca_libros_paginas check (paginas is null or paginas >= 0),
  constraint biblioteca_libros_pagina_actual check (pagina_actual is null or pagina_actual >= 0),
  unique(owner_id, legacy_id)
);

create table if not exists public.biblioteca_lecturas (
  id bigint generated by default as identity primary key,
  owner_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  legacy_id bigint,
  libro_id bigint not null references public.biblioteca_libros(id) on delete cascade,
  fecha date not null,
  pagina integer,
  paginas_leidas integer not null default 0,
