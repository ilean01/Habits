do $$
declare t text;
begin
  foreach t in array array[
    'biblioteca_libros',
    'biblioteca_lecturas',
    'biblioteca_lecturas_finalizadas',
    'biblioteca_personas',
    'biblioteca_prestamos',
    'biblioteca_config'
  ] loop
    execute format('drop policy if exists %I on public.%I', t || '_private', t);
    execute format(
      'create policy %I on public.%I for all to authenticated using (owner_id = (select auth.uid()) and public.has_biblioteca_access()) with check (owner_id = (select auth.uid()) and public.has_biblioteca_access())',
      t || '_private', t
    );
  end loop;
end $$;

create or replace function public.biblioteca_touch_updated_at()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists biblioteca_libros_touch on public.biblioteca_libros;
create trigger biblioteca_libros_touch before update on public.biblioteca_libros
for each row execute function public.biblioteca_touch_updated_at();

drop trigger if exists biblioteca_prestamos_touch on public.biblioteca_prestamos;
create trigger biblioteca_prestamos_touch before update on public.biblioteca_prestamos
for each row execute function public.biblioteca_touch_updated_at();

drop trigger if exists biblioteca_config_touch on public.biblioteca_config;
create trigger biblioteca_config_touch before update on public.biblioteca_config
for each row execute function public.biblioteca_touch_updated_at();

-- Bucket privado para portadas. Cada archivo se guarda bajo <auth.uid()>/...
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values (
  'biblioteca-portadas',
  'biblioteca-portadas',
  false,
  10485760,
  array['image/jpeg','image/png','image/webp','image/gif']
)
on conflict (id) do update set
  public = excluded.public,
  file_size_limit = excluded.file_size_limit,
  allowed_mime_types = excluded.allowed_mime_types;

drop policy if exists biblioteca_portadas_select on storage.objects;
create policy biblioteca_portadas_select on storage.objects
for select to authenticated
using (
  bucket_id = 'biblioteca-portadas'
  and public.has_biblioteca_access()
  and (storage.foldername(name))[1] = (select auth.uid())::text
);

drop policy if exists biblioteca_portadas_insert on storage.objects;
